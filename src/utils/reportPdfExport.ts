/**
 * Executive MIS Report PDF Generator
 * Renders professional Kumkang Kind MIS reports with executive letterhead, KPI summaries, and data tables.
 */

export interface MISReportPDFOptions {
  title: string;
  subtitle: string;
  cadence: 'Weekly' | 'Monthly' | 'Annual';
  kpis: Array<{ label: string; value: string }>;
  headers: string[];
  rows: Array<Array<string | number>>;
}

export function generateReportPDF(options: MISReportPDFOptions) {
  const printWindow = window.open('', '_blank');
  if (!printWindow) {
    alert('Please allow popups to export the report to PDF.');
    return;
  }

  const today = new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' });
  const time = new Date().toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' });

  const html = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>${options.title} - Kumkang Kind MIS</title>
  <style>
    @page { size: A4 landscape; margin: 12mm; }
    body {
      font-family: 'Segoe UI', -apple-system, BlinkMacSystemFont, Roboto, sans-serif;
      color: #0F172A;
      background: #FFFFFF;
      margin: 0;
      padding: 20px;
      font-size: 11px;
    }
    .header {
      border-bottom: 2px solid #0E4E8A;
      padding-bottom: 12px;
      margin-bottom: 16px;
      display: flex;
      justify-content: space-between;
      align-items: flex-end;
    }
    .brand {
      font-size: 20px;
      font-weight: 900;
      color: #0B2239;
      letter-spacing: 0.5px;
    }
    .brand-sub {
      font-size: 10px;
      font-weight: 700;
      color: #0284C7;
      text-transform: uppercase;
    }
    .doc-meta {
      text-align: right;
      font-size: 10px;
      color: #64748B;
    }
    .cadence-badge {
      display: inline-block;
      padding: 3px 8px;
      background: #E0F2FE;
      color: #0369A1;
      font-weight: 800;
      border-radius: 4px;
      font-size: 10px;
      text-transform: uppercase;
      margin-bottom: 4px;
    }
    .kpi-grid {
      display: grid;
      grid-template-columns: repeat(${options.kpis.length}, 1fr);
      gap: 12px;
      margin-bottom: 16px;
    }
    .kpi-card {
      background: #F8FAFC;
      border: 1px solid #E2E8F0;
      border-radius: 6px;
      padding: 8px 12px;
    }
    .kpi-label {
      font-size: 9px;
      font-weight: 700;
      text-transform: uppercase;
      color: #64748B;
      margin-bottom: 2px;
    }
    .kpi-value {
      font-size: 14px;
      font-weight: 800;
      color: #0F172A;
    }
    table {
      width: 100%;
      border-collapse: collapse;
      margin-top: 10px;
    }
    th {
      background: #0E4E8A;
      color: #FFFFFF;
      font-size: 10px;
      font-weight: 800;
      text-align: left;
      padding: 7px 10px;
      border: 1px solid #0E4E8A;
      text-transform: uppercase;
    }
    td {
      padding: 6px 10px;
      border: 1px solid #E2E8F0;
      font-size: 10.5px;
    }
    tr:nth-child(even) td {
      background: #F8FAFC;
    }
    .footer {
      border-top: 1px solid #E2E8F0;
      padding-top: 12px;
      margin-top: 24px;
      font-size: 9px;
      color: #64748B;
      display: flex;
      justify-content: space-between;
    }
  </style>
</head>
<body>
  <div class="header">
    <div>
      <div class="brand">KUMKANG KIND</div>
      <div class="brand-sub">Management Information System · Official Executive Report</div>
      <h2 style="margin: 8px 0 0 0; font-size: 16px; color: #0F172A;">${options.title}</h2>
      <div style="font-size: 10px; color: #64748B;">${options.subtitle}</div>
    </div>
    <div class="doc-meta">
      <div class="cadence-badge">${options.cadence} Cadence</div>
      <div>Generated: ${today} at ${time}</div>
      <div>Source: Kumkang Enterprise Live Operational Database</div>
    </div>
  </div>

  <div class="kpi-grid">
    ${options.kpis.map(k => `
      <div class="kpi-card">
        <div class="kpi-label">${k.label}</div>
        <div class="kpi-value">${k.value}</div>
      </div>
    `).join('')}
  </div>

  <table>
    <thead>
      <tr>
        ${options.headers.map(h => `<th>${h}</th>`).join('')}
      </tr>
    </thead>
    <tbody>
      ${options.rows.map(row => `
        <tr>
          ${row.map(cell => `<td>${cell !== undefined && cell !== null ? cell : '—'}</td>`).join('')}
        </tr>
      `).join('')}
    </tbody>
  </table>

  <div class="footer">
    <div>Classification: Executive Confidential · Kumkang Kind India & Global Operations</div>
    <div>System Certified · Page 1 of 1 · Auto-Generated by MIS Automation Engine</div>
  </div>

  <script>
    window.onload = function() {
      setTimeout(function() {
        window.print();
      }, 500);
    };
  </script>
</body>
</html>`;

  printWindow.document.write(html);
  printWindow.document.close();
}
